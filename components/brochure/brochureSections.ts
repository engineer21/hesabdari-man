function normalizeQuery(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/\u200c/g, ' ')
    .replace(/\s+/g, ' ');
}

export function filterBrochureSections(
  query: string,
  sections: BrochureSection[] = brochureSections
): BrochureSection[] {
  const q = normalizeQuery(query);
  if (!q) return sections;
  const tokens = q.split(' ').filter(Boolean);
  return sections.filter((section) => {
    const haystack = normalizeQuery(
      [
        section.title,
        section.eyebrow,
        section.description,
        ...section.highlights,
        ...section.details,
        ...section.keywords,
      ].join(' ')
    );
    return tokens.every((tok) => haystack.includes(tok));
  });
}
