export function resolvePageHelp(view: string): PageHelpContent {
  return (
    PAGE_HELP[view] || {
      id: view,
      title: 'راهنما',
      subtitle: 'این بخش',
      tips: [{ title: 'کمک', body: 'از منوی تنظیمات، راهنمای کامل نرم‌افزار را باز کنید.' }],
    }
  );
}

export function viewToBrochureId(view: string): string | undefined {
  return resolvePageHelp(view).brochureSectionId;
}
